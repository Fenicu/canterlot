//! Файлы, которые утилита пишет на хост: compose, Caddyfile, hub.toml, worker.toml, юнит.
//! Всё детерминировано: одинаковое состояние даёт байт-в-байт одинаковый файл, поэтому
//! установка и обновление просто перерисовывают их.

use std::{fmt::Write as _, net::SocketAddr, path::Path};

use url::Url;

use crate::{
    cli::{TlsMode, Version},
    error::CtlError,
    state::InstallState,
    worker::{DetectedAgent, Harness, MachineIds},
};

/// Образ PostgreSQL с закреплённой младшей версией: та же, что у тестовой базы.
pub const POSTGRES_IMAGE: &str = "postgres:18.6-trixie";
pub const HUB_IMAGE: &str = "debian:trixie-slim";
pub const CADDY_IMAGE: &str = "caddy:2";
/// Подсеть compose фиксирована: хаб доверяет ровно ей как адресам внутреннего Caddy.
pub const COMPOSE_SUBNET: &str = "172.30.231.0/24";
pub const HUB_UID: u32 = 980;
pub const HUB_GID: u32 = 980;
pub const DEFAULT_GRPC_PORT: u16 = 7443;
/// Порт, на котором внутренний Caddy в режиме `external` ждёт внешний прокси.
pub const EXTERNAL_BACKEND_PORT: u16 = 8080;
/// Пример адреса PWA, с которым выпуск публикует `canterlot-csp-X.txt`.
const CSP_SAMPLE_WSS: &str = "wss://chat.example.com";

/// Пути внутри контейнеров. Хост-пути совпадают с ними, кроме каталогов релиза и веба.
pub const HUB_BIN: &str = "/opt/canterlot/hub/current/bin/canterlot-hub";
pub const HUB_CONFIG: &str = "/etc/canterlot/hub/hub.toml";

const HEADER: &str = "# Generated by canterlot; rewritten on every install and update.\n";

fn host_of(origin: &str) -> String {
    Url::parse(origin)
        .ok()
        .and_then(|url| url.host_str().map(str::to_owned))
        .unwrap_or_else(|| origin.to_owned())
}

/// Порт из `host:port` точки gRPC; без порта — стандартный.
pub fn grpc_port(s: &InstallState) -> u16 {
    s.grpc_endpoint
        .as_deref()
        .and_then(|endpoint| endpoint.rsplit_once(':'))
        .and_then(|(_, port)| port.parse().ok())
        .unwrap_or(DEFAULT_GRPC_PORT)
}

/// Имя или адрес из `host:port` (IPv6 в квадратных скобках).
pub fn endpoint_host(endpoint: &str) -> String {
    let host = match endpoint.rsplit_once(':') {
        Some((host, port)) if port.bytes().all(|b| b.is_ascii_digit()) => host,
        _ => endpoint,
    };
    host.trim_start_matches('[')
        .trim_end_matches(']')
        .to_owned()
}

/// CSP выпуска собран для примера `chat.example.com`; подставляем хост своего PWA.
pub fn csp_for_origin(csp_txt: &str, origin: &str) -> Result<String, CtlError> {
    let csp = csp_txt.trim();
    if !csp.contains(CSP_SAMPLE_WSS) {
        return Err(CtlError::Other(format!(
            "csp_invalid: release CSP lacks {CSP_SAMPLE_WSS}"
        )));
    }
    // Значение встаёт в кавычки Caddyfile: кавычки и переводы строк сломали бы файл.
    if csp.contains(['"', '\n', '\r', '{', '}']) {
        return Err(CtlError::Other(
            "csp_invalid: release CSP has characters not allowed in the Caddyfile".into(),
        ));
    }
    Ok(csp.replace(CSP_SAMPLE_WSS, &format!("wss://{}", host_of(origin))))
}

fn hub_volumes(out: &mut String, release: &str, manifest_rw: bool) {
    let manifest = if manifest_rw { "" } else { ":ro" };
    let _ = write!(
        out,
        "    volumes:\n      - {release}:/opt/canterlot/hub/current:ro\n      - /etc/canterlot/hub:/etc/canterlot/hub:ro\n      - /etc/canterlot/manifest:/etc/canterlot/manifest{manifest}\n      - /var/lib/canterlot/hub:/var/lib/canterlot/hub\n"
    );
}

fn command(args: &[&str]) -> String {
    let quoted: Vec<String> = args.iter().map(|a| format!("\"{a}\"")).collect();
    format!("[{}]", quoted.join(", "))
}

pub fn render_compose(s: &InstallState, v: &Version) -> String {
    let release = format!("/opt/canterlot/hub/releases/{}", v.as_str());
    let user = format!("\"{}:{}\"", s.hub_uid, s.hub_gid);
    let mut out = String::from(HEADER);
    out.push_str("name: canterlot\nservices:\n");
    let _ = write!(
        out,
        "  postgres:\n    image: {POSTGRES_IMAGE}\n    restart: unless-stopped\n    environment:\n      POSTGRES_PASSWORD_FILE: /run/secrets/postgres-superuser\n    volumes:\n      - /var/lib/canterlot/postgres:/var/lib/postgresql\n      - /etc/canterlot/compose/postgres.secret:/run/secrets/postgres-superuser:ro\n    networks:\n      - canterlot\n"
    );
    let _ = write!(
        out,
        "  hub:\n    image: {HUB_IMAGE}\n    restart: unless-stopped\n    user: {user}\n    command: {}\n    depends_on:\n      - postgres\n",
        command(&[HUB_BIN, "serve", "--config", HUB_CONFIG])
    );
    hub_volumes(&mut out, &release, false);
    let _ = write!(
        out,
        "    ports:\n      - \"{}:7443\"\n    networks:\n      - canterlot\n",
        grpc_port(s)
    );
    // Отдельная служба для `init`: только ей манифест доступен на запись, `up` её не трогает.
    let _ = write!(
        out,
        "  hub-init:\n    image: {HUB_IMAGE}\n    profiles:\n      - init\n    user: {user}\n    command: {}\n    depends_on:\n      - postgres\n",
        command(&[HUB_BIN, "init", "--config", HUB_CONFIG])
    );
    hub_volumes(&mut out, &release, true);
    out.push_str("    networks:\n      - canterlot\n");
    // Каталог Caddyfile монтируется целиком: атомарная замена файла меняет inode,
    // и смонтированный по отдельности файл остался бы старым.
    let _ = write!(
        out,
        "  caddy:\n    image: {CADDY_IMAGE}\n    restart: unless-stopped\n    depends_on:\n      - hub\n    volumes:\n      - /opt/canterlot/web:/srv/canterlot-web:ro\n      - /etc/canterlot/compose/caddy:/etc/caddy:ro\n      - /etc/canterlot/hub/proxy.secret:/run/secrets/canterlot-proxy:ro\n      - /var/lib/canterlot/caddy:/data\n    ports:\n"
    );
    // Публикация через iptables DNAT сохраняет адрес клиента, поэтому {remote_host}
    // в краевых режимах — настоящий клиент, а не шлюз моста.
    match s.tls {
        Some(TlsMode::External) => {
            let _ = writeln!(out, "      - \"{EXTERNAL_BACKEND_PORT}:80\"");
        }
        Some(TlsMode::SelfSigned) => out.push_str("      - \"443:443\"\n"),
        Some(TlsMode::Acme) | None => {
            out.push_str("      - \"80:80\"\n      - \"443:443\"\n      - \"443:443/udp\"\n")
        }
    }
    let _ = write!(
        out,
        "    networks:\n      - canterlot\nnetworks:\n  canterlot:\n    ipam:\n      config:\n        - subnet: {COMPOSE_SUBNET}\n"
    );
    out
}

/// Добавка к compose на время проверки нового хаба: gRPC не публикуется наружу.
pub fn render_compose_fenced() -> String {
    format!("{HEADER}services:\n  hub:\n    ports: !reset []\n")
}

pub fn render_caddyfile(s: &InstallState, csp: &str) -> String {
    let origin = s.origin.as_deref().unwrap_or("https://localhost");
    let host = host_of(origin);
    let mut out = String::new();
    let client_ip = match s.tls {
        Some(TlsMode::External) => {
            // Внешнему прокси доверяем ровно по его адресу; strict берёт адрес справа,
            // то есть дописанный самим прокси, а не присланный клиентом.
            let front = s
                .front_ip
                .map(|ip| match ip {
                    std::net::IpAddr::V4(_) => format!("{ip}/32"),
                    std::net::IpAddr::V6(_) => format!("{ip}/128"),
                })
                .unwrap_or_default();
            let _ = write!(
                out,
                "{{\n    servers {{\n        trusted_proxies static {front}\n        trusted_proxies_strict\n    }}\n}}\n\n:80 {{\n"
            );
            "{client_ip}"
        }
        Some(TlsMode::SelfSigned) => {
            let _ = write!(out, "{host} {{\n    tls internal\n");
            "{remote_host}"
        }
        Some(TlsMode::Acme) | None => {
            let _ = writeln!(out, "{host} {{");
            "{remote_host}"
        }
    };
    // Порядок директив — канонический блок docs/pwa.md; матчер обслуживания стоит до @api,
    // чтобы во время обновления API отвечал 503, а статика продолжала раздаваться.
    let _ = write!(
        out,
        r#"    route {{
        request_header -Remote-*
        request_header -X-Forwarded-*
        request_header -X-Canterlot-Proxy
        request_header -X-Canterlot-Client-Ip
        header Content-Security-Policy "{csp}"
        header X-Content-Type-Options "nosniff"
        @maint {{
            path /api/*
            file {{
                root /srv/canterlot-web
                try_files /maintenance
            }}
        }}
        handle @maint {{
            header Content-Type "application/json"
            respond `{{"error":"maintenance"}}` 503
        }}
        @api path /api/* /healthz
        handle @api {{
            encode zstd gzip
            reverse_proxy hub:8080 {{
                header_up X-Canterlot-Proxy {{file./run/secrets/canterlot-proxy}}
                header_up X-Canterlot-Client-Ip {client_ip}
            }}
        }}
        @share {{
            method POST
            path /_share
        }}
        handle @share {{
            redir * /share?error=sw_inactive 303
        }}
        handle {{
            @fresh path /manifest.webmanifest
            header @fresh Cache-Control "no-cache"
            root * /srv/canterlot-web/build
            try_files {{path}} /200.html
            file_server {{
                precompressed zstd br gzip
            }}
        }}
    }}
}}
"#
    );
    out
}

/// Строка TOML с экранированием.
fn q(text: &str) -> String {
    toml::Value::String(text.to_owned()).to_string()
}

pub fn render_hub_toml(s: &InstallState) -> String {
    let origin = s.origin.as_deref().unwrap_or("https://localhost");
    let login = s.owner_login.as_deref().unwrap_or("owner");
    let mut out = String::from(HEADER);
    out.push_str(
        r#"database_url_file = "/etc/canterlot/hub/db.url"
grpc_listen = "0.0.0.0:7443"
tls_cert = "/etc/canterlot/hub/tls/hub.crt"
tls_key = "/etc/canterlot/hub/tls/hub.key"
tls_ca = "/etc/canterlot/hub/tls/ca.crt"
manifest = "/etc/canterlot/manifest/installation.toml"

[http]
listen = "0.0.0.0:8080"
"#,
    );
    let _ = write!(
        out,
        "trusted_proxies = [{}]\nowner_login = {}\nallowed_origins = [{}]\nproxy_secret_file = \"/etc/canterlot/hub/proxy.secret\"\n",
        q(COMPOSE_SUBNET),
        q(login),
        q(origin)
    );
    out.push_str(
        r#"
[attachments]
blob_dir = "/var/lib/canterlot/hub/attachments"

[auth.geoip]
path = "/var/lib/canterlot/hub/geoip/dbip-city-lite.mmdb"
"#,
    );
    if let Some(endpoint) = &s.grpc_endpoint {
        let _ = write!(out, "\n[enroll]\ngrpc_endpoint = {}\n", q(endpoint));
    }
    out
}

pub fn render_worker_toml(
    hub: &str,
    ids: &MachineIds,
    home: &Path,
    agents: &[DetectedAgent],
) -> String {
    let path = |rel: &str| q(&home.join(rel).to_string_lossy());
    let mut out = String::from(HEADER);
    let _ = write!(
        out,
        "hub_url = {}\nca_cert = {}\ntoken_file = {}\nmachine_id = \"{}\"\ninstallation_id = \"{}\"\nrestore_generation = \"{}\"\ndata_dir = {}\n\n[execution]\nallowed_workdir_roots = [{}]\n",
        q(hub),
        path(".config/canterlot/ca.pem"),
        path(".config/canterlot/token"),
        ids.machine_id,
        ids.installation_id,
        ids.restore_generation,
        path(".local/state/canterlot-worker"),
        q(&home.to_string_lossy()),
    );
    for agent in agents {
        let table = match agent.harness {
            Harness::ClaudeCode => "claude_code",
            Harness::Codex => "codex",
            Harness::OpenCode => "opencode",
        };
        let _ = write!(
            out,
            "\n[{table}]\nexecutable = {}\n",
            q(&agent.executable.to_string_lossy())
        );
    }
    out
}

/// Юнит из pilot.md §6.4; бинарь берётся из `current`, чтобы обновление меняло только ссылку.
pub fn render_worker_unit() -> String {
    r#"[Unit]
Description=Canterlot Execution Worker
After=default.target

[Service]
Type=notify
NotifyAccess=main
WorkingDirectory=%h
ExecStart=%h/.local/opt/canterlot/current/bin/canterlot-worker run --config %h/.config/canterlot/worker.toml
Restart=always
RestartSec=3s
TimeoutStartSec=5min
WatchdogSec=60
KillMode=process
LimitNOFILE=65536

[Install]
WantedBy=default.target
"#
    .to_owned()
}

/// Блок для внешнего Caddy: он затирает присланный клиентом X-Forwarded-For своим пиром.
pub fn render_front_block(s: &InstallState, backend: SocketAddr) -> String {
    let host = host_of(s.origin.as_deref().unwrap_or("https://localhost"));
    format!(
        "{host} {{\n    reverse_proxy {backend} {{\n        header_up X-Forwarded-For {{remote_host}}\n        header_up -X-Canterlot-Proxy\n        header_up -X-Canterlot-Client-Ip\n    }}\n}}\n"
    )
}
