/**
 * Состояние значка «Чернила»:
 * - `sketch` — дело идёт: бледный контур дышит;
 * - `ink` — дело завершилось на глазах: контур один раз прописывается и цвет оседает;
 * - `dry` — дело завершено давно или не на глазах: значок стоит написанным;
 * - `refused` — ничего не записано: приглушённый контур остаётся наброском.
 */
export type InkState = 'sketch' | 'ink' | 'dry' | 'refused';
